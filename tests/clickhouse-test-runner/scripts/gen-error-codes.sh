#!/usr/bin/env bash
# Generates src/errorcodes.rs from src/Common/ErrorCodes.cpp of a ClickHouse
# checkout. fetch-upstream.sh runs it after each checkout, so the error names
# of the test hints always match the tests. It needs only bash, sed and grep
# (no Rust toolchain); the output is already in rustfmt style.
#
# Usage: scripts/gen-error-codes.sh [<ClickHouse checkout>]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUNNER_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
checkout="${1:-${UPSTREAM_CLICKHOUSE_DIR:-${RUNNER_DIR}/.upstream/ClickHouse}}"
src_file="${checkout}/src/Common/ErrorCodes.cpp"

if [[ ! -f "${src_file}" ]]; then
  echo "Error: ${src_file} not found. Run ${SCRIPT_DIR}/fetch-upstream.sh first." >&2
  exit 1
fi
ref="$(cat "${checkout}/.upstream-ref" 2>/dev/null || git -C "${checkout}" rev-parse HEAD)"

out="${RUNNER_DIR}/src/errorcodes.rs"
{
  echo "// Code generated by scripts/gen-error-codes.sh from ClickHouse ${ref}; DO NOT EDIT."
  echo
  echo "//! The error names of ClickHouse's \`src/Common/ErrorCodes.cpp\` and their codes."
  echo "//! Test hints can name an error instead of giving its code."
  echo
  echo "#[rustfmt::skip]"
  echo "pub(crate) const ERROR_CODES: &[(&str, i32)] = &["
  sed -n 's/^ *M(\([0-9][0-9]*\), *\([A-Z0-9_][A-Z0-9_]*\)).*/    ("\2", \1),/p' "${src_file}"
  echo "];"
} > "${out}"
echo "Wrote $(grep -c '^    ("' "${out}") error codes from ${ref} to ${out}" >&2
